def _block_specs() -> list[CircuitSpec]:
    return [load_circuit(CIRCUITS_DIR / b / f"{b}.yaml") for b in BLOCK_IDS]


def compose_netlist(blocks: list[CircuitSpec]) -> str:
    header = textwrap.dedent(
        """\
        * Differential reference circuit - Reference Channel Strip (composite)
        * ---------------------------------------------------------------------------
        * GENERATED by differential/circuits/compose.py from the five block netlists;
        * edit the blocks, not this file. Original generic design written for this
        * project. Block 1 (PSU) powers blocks 2-5; signal path: triode stage ->
        * passive Baxandall tone control -> op-amp make-up gain -> BJT line driver.
        * Fixtures: signal generator VIN (600 ohm source) and a 10k external load.
        * Run standalone: ngspice -b circuits/channel_strip/channel_strip.cir
        * ---------------------------------------------------------------------------
        .include ../lib/devices.lib
        """
    )
    lines = [header.rstrip("\n"), "", "* ---- Fixtures: signal generator and external load ----"]
    for spec in blocks:
        for el in spec.netlist.elements:
            if el.name in KEEP_FIXTURES:
                lines.append(el.line())
    for spec in blocks:
        lines.append("")
        lines.append(f"* ---- {spec.name} ----")
        for el in spec.netlist.elements:
            if el.name in spec.fixtures:
                continue
            lines.append(el.line())
    lines += [
        "",
        ".control",
        "set noaskquit",
        "op",
        "print v(vunreg) v(vreg) v(bplus) v(plate) v(cath) v(vref) v(q1c) v(q2e) v(out)",
        "ac lin 1 1000 1000",
        "print mag(v(out))",
        ".endc",
        ".end",
    ]
    return "\n".join(lines) + "\n"


def _num(v: float) -> float | int:
    return int(v) if float(v).is_integer() else v


def compose_sidecar(blocks: list[CircuitSpec]) -> dict[str, Any]:
    by_id = {b.id: b for b in blocks}
    stages: list[dict[str, str]] = []
    components: list[dict[str, Any]] = []
    infra: list[str] = []
    tp_lookup: dict[str, Any] = {}
    for b in blocks:
        for sid, name in b.stages:
            stages.append({"id": sid, "name": name})
        infra += b.infrastructure
        raw = yaml.safe_load((b.netlist_path.parent / f"{b.id}.yaml").read_text())
        components += raw["components"]
        for tp in raw["test_points"]:
            tp_lookup.setdefault(tp["id"], tp)
    tps = []
    for tp_id, tp_name, meas, hint in COMPOSITE_TPS:
        base = dict(tp_lookup[tp_id])
        if tp_name:
            base["name"] = tp_name
        if hint:
            base["hint"] = hint
        base["measurements"] = meas
        tps.append(base)
    psu_raw = yaml.safe_load((by_id["psu"].netlist_path.parent / "psu.yaml").read_text())
    # The composite's highest supply is its blocks' highest; its model counts as validated
    # only if every block's model is (ADR-034).
    supplies = [b.declared_supply_v for b in blocks if b.declared_supply_v is not None]
    evidence = sorted({b.validation_evidence for b in blocks if b.model_validated})
    validation = ({"status": "validated", "evidence": "; ".join(evidence)}
                  if all(b.model_validated for b in blocks) else {"status": "not validated"})
    return {
        "id": COMPOSITE_ID,
        "name": "Reference Channel Strip",
        "netlist": f"{COMPOSITE_ID}.cir",
        **({"declared_supply_v": _num(max(supplies))} if supplies else {}),
        "model_validation": validation,
        "generated_by": "differential/circuits/compose.py",
        "description": (
            "Composite hero circuit: the power supply block powers a 12AX7-class triode "
            "stage, a passive Baxandall tone control, an op-amp make-up gain stage and a "
            "discrete BJT line driver. About 1 V rms at the line output for a 15.6 mV rms "
            "input at 1 kHz, with the tone controls centred."
        ),
        "blocks": list(BLOCK_IDS),
        "stages": stages,
        "signal": {
            "source": "VIN",
            "output_node": "out",
            "tran_amplitude": COMPOSITE_TRAN_AMPLITUDE,
            "frequency": 1000,
        },
        "hum": psu_raw["hum"],
        "fixtures": sorted(KEEP_FIXTURES),
        "infrastructure": infra,
        "components": components,
        "test_points": tps,
        "service_notes": SERVICE_NOTES,
    }


class _FlowDumper(yaml.SafeDumper):
    pass


def _dict_representer(dumper: yaml.SafeDumper, data: dict[str, Any]) -> yaml.Node:
    flow = (all(not isinstance(v, (dict, list)) or k in {"elements", "params", "measurements"}
               for k, v in data.items()) and "ref" in data) or "node" in data
    return dumper.represent_mapping("tag:yaml.org,2002:map", data.items(), flow_style=flow)


_FlowDumper.add_representer(dict, _dict_representer)


def compose(write: bool = True) -> tuple[str, str]:
    blocks = _block_specs()
    net_text = compose_netlist(blocks)
    side = compose_sidecar(blocks)
    yaml_text = (
        "# GENERATED by differential/circuits/compose.py - edit the block sidecars instead.\n"
        + yaml.dump(side, Dumper=_FlowDumper, sort_keys=False, width=100, allow_unicode=True)
    )
    if write:
        out_dir: Path = CIRCUITS_DIR / COMPOSITE_ID
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir / f"{COMPOSITE_ID}.cir").write_text(net_text)
        (out_dir / f"{COMPOSITE_ID}.yaml").write_text(yaml_text)
    return net_text, yaml_text


if __name__ == "__main__":
    compose()
